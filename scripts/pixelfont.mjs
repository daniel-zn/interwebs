  M: '10001 11011 10101 10001 10001', N: '10001 11001 10101 10011 10001', O: '01110 10001 10001 10001 01110',
  P: '11110 10001 11110 10000 10000', Q: '01110 10001 10101 10010 01101', R: '11110 10001 11110 10010 10001',
